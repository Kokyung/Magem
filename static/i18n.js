/** Map the OS's preferred languages onto the supported list (Chinese and Spanish by region); else English. */
function detectLanguage(preferred) {
  for (const raw of preferred || []) {
    const l = String(raw).toLowerCase().replace("_", "-");
    if (l.startsWith("zh")) return /hant|-tw|-hk|-mo/.test(l) ? "zh-TW" : "zh-CN";
    if (l.startsWith("es")) return l === "es" || l === "es-es" ? "es-ES" : "es-419";
    const base = l.split("-")[0];
    if (MESSAGES[base]) return base;
  }
  return "en";
}
